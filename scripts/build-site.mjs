// Puts whiskedaway.com together after `vite build` (docs/front-door-spec.md):
//   /            the 360° Inn with its front door (public/explore/index.html, made by build-explore.mjs)
//   /explore/    its room data, renders and scripts; /explore/ itself forwards to / with the query kept
//   /archive/    the old React Inn (vite builds it there), with a page for each of its routes
//   /_redirects  old links: rooms that exist in the 360° Inn go there, the rest to the archive
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'public');
const dist = join(root, 'dist');
if (!existsSync(join(dist, 'archive', 'index.html'))) throw new Error('run vite build first (dist/archive/index.html is missing)');

// Site-wide files (favicon, robots.txt, _headers, the share image) at the root
for (const f of readdirSync(pub)) if (f !== 'explore') cpSync(join(pub, f), join(dist, f), { recursive: true });

// The Inn's files stay under /explore/; the page itself moves to / and finds them through <base>
cpSync(join(pub, 'explore'), join(dist, 'explore'), { recursive: true, filter: src => src !== join(pub, 'explore', 'index.html') });
const inn = readFileSync(join(pub, 'explore', 'index.html'), 'utf8');
if (!inn.includes('<head>')) throw new Error('explore page has no <head>');
writeFileSync(join(dist, 'index.html'), inn.replace('<head>', '<head>\n<base href="/explore/">'));

// /explore/ used to be the Inn's address: send it home, keeping ?room= and the like
writeFileSync(join(dist, 'explore', 'index.html'), `<!doctype html>
<meta charset="utf-8">
<title>WhiskedAway</title>
<link rel="canonical" href="https://whiskedaway.com/">
<meta name="robots" content="noindex">
<script>location.replace('/' + location.search + location.hash)</script>
<p>The Inn has moved to <a href="/">whiskedaway.com</a>.</p>
`);

// The archive is a single-page app under /archive/: give each of its routes a copy of its page, so a
// reload or a shared link lands on the right scene (the site's own fallback only knows the root page)
const archive = readFileSync(join(dist, 'archive', 'index.html'));
const scenes = ['cuddlecore', 'flourish', 'cravings', 'sweet-spells', 'chiapothecary', 'academy'];
mkdirSync(join(dist, 'archive', 'original'), { recursive: true });
for (const p of [...scenes, 'original', ...scenes.map(s => `original/${s}`)]) writeFileSync(join(dist, 'archive', `${p}.html`), archive);

// Old links. Redirects run before assets, so nothing here may match a real file.
writeFileSync(join(dist, '_redirects'), [
  '# Generated by scripts/build-site.mjs',
  '/cuddlecore /?room=cuddlecore 301',
  '/flourish /?room=flourish 301',
  '/sweet-spells /?room=sweet-spells 301',
  '/chiapothecary /?room=chiapothecary 301',
  ...['cravings', 'academy'].map(s => `/${s} /archive/${s} 301`),
  '/original /archive/original 301',
  '/original/* /archive/original/:splat 301',
  '',
].join('\n'));

writeFileSync(join(dist, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>https://whiskedaway.com/</loc></url>
</urlset>
`);
console.log('site: / is the Inn, /archive/ the old app, redirects and sitemap written');
